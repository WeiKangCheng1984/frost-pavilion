import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";
import { CELL, COLUMNS, FRAME_NAMES } from "../src/sprite-frames.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const palette = new Map();
for (const line of fs.readFileSync(path.join(root, "assets/palette.txt"), "utf8").split(/\r?\n/)) {
  const trimmed = line.trim();
  if (!trimmed) continue;
  const [index, hex] = trimmed.split(/\s+/);
  palette.set(index, hex.slice(1));
}
if (palette.size > 16) throw new Error("色盤超過 16 色");

function blank() {
  return Array.from({ length: CELL }, () => Array(CELL).fill("."));
}

function fill(color) {
  return Array.from({ length: CELL }, () => Array(CELL).fill(color));
}

function put(grid, x, y, color) {
  if (x < 0 || y < 0 || x >= CELL || y >= CELL || color === ".") return;
  grid[y][x] = color;
}

function rect(grid, x, y, w, h, color) {
  for (let yy = y; yy < y + h; yy += 1) {
    for (let xx = x; xx < x + w; xx += 1) put(grid, xx, yy, color);
  }
}

function frame(grid, x, y, w, h, color) {
  for (let xx = x; xx < x + w; xx += 1) {
    put(grid, xx, y, color);
    put(grid, xx, y + h - 1, color);
  }
  for (let yy = y; yy < y + h; yy += 1) {
    put(grid, x, yy, color);
    put(grid, x + w - 1, yy, color);
  }
}

function parse(art) {
  const rows = art.trim().split(/\n/).map((row) => row.trim());
  if (rows.length !== CELL) throw new Error(`需要 ${CELL} 行，得到 ${rows.length}`);
  return rows.map((row) => {
    if (row.length !== CELL) throw new Error(`行寬 ${row.length}：${row}`);
    return row.split("");
  });
}

function brick() {
  const grid = blank();
  for (let y = 0; y < CELL; y += 1) {
    const odd = Math.floor(y / 8) % 2 === 1;
    const mortarRow = y % 8 === 7;
    for (let x = 0; x < CELL; x += 1) {
      const joint = ((x + (odd ? 4 : 0)) % 8) === 0;
      grid[y][x] = mortarRow || joint ? "1" : ((x + y) % 7 === 0 ? "2" : "3");
    }
  }
  return grid;
}

function trigram(bits) {
  const grid = fill("2");
  rect(grid, 2, 2, 12, 12, "6");
  frame(grid, 1, 1, 14, 14, "0");
  bits.forEach((solid, index) => {
    const y = 4 + index * 3;
    const paintLine = (from, to) => {
      for (let x = from; x <= to; x += 1) {
        put(grid, x, y, "0");
        put(grid, x, y + 1, "0");
      }
    };
    if (solid) paintLine(3, 12);
    else {
      paintLine(3, 6);
      paintLine(9, 12);
    }
  });
  return grid;
}

function screen() {
  const grid = fill(".");
  rect(grid, 0, 1, 16, 13, "1");
  for (let pane = 0; pane < 4; pane += 1) {
    const x = 1 + pane * 4;
    rect(grid, x, 2, 3, 11, "6");
    put(grid, x + 1, 4, "7");
    put(grid, x + 1, 7, "5");
    put(grid, x + 1, 10, "0");
  }
  frame(grid, 0, 1, 16, 13, "0");
  return grid;
}

function tiles() {
  const grid = fill("1");
  const colors = ["d", "b", "e", "8", "5"];
  colors.forEach((color, index) => {
    const x = 1 + index * 3;
    rect(grid, x, 4, 2, 8, "0");
    rect(grid, x, 5, 2, 6, color);
  });
  return grid;
}

function element(mark) {
  const grid = fill("3");
  frame(grid, 0, 0, 16, 16, "1");
  frame(grid, 2, 2, 12, 12, "0");
  rect(grid, 4, 4, 8, 8, "6");
  for (let y = 0; y < mark.length; y += 1) {
    for (let x = 0; x < mark[y].length; x += 1) {
      if (mark[y][x] !== ".") put(grid, 4 + x, 4 + y, mark[y][x]);
    }
  }
  return grid;
}

