for (const name of FRAME_NAMES) {
  if (!pictures[name]) throw new Error(`缺圖：${name}`);
}
for (const name of Object.keys(pictures)) {
  if (!FRAME_NAMES.includes(name)) throw new Error(`多了圖：${name}`);
}

const rows = Math.ceil(FRAME_NAMES.length / COLUMNS);
const width = COLUMNS * CELL;
const height = rows * CELL;
const rgba = Buffer.alloc(width * height * 4);

function paint(index, grid) {
  const ox = (index % COLUMNS) * CELL;
  const oy = Math.floor(index / COLUMNS) * CELL;
  for (let y = 0; y < CELL; y += 1) {
    for (let x = 0; x < CELL; x += 1) {
      const color = grid[y][x];
      const at = ((oy + y) * width + (ox + x)) * 4;
      if (color === ".") continue;
      const hex = palette.get(color);
      if (!hex) throw new Error(`未知色 ${color}`);
      rgba[at] = Number.parseInt(hex.slice(0, 2), 16);
      rgba[at + 1] = Number.parseInt(hex.slice(2, 4), 16);
      rgba[at + 2] = Number.parseInt(hex.slice(4, 6), 16);
      rgba[at + 3] = 255;
    }
  }
}

FRAME_NAMES.forEach((name, index) => paint(index, pictures[name]));

function crc32(buffer) {
  let crc = 0xffffffff;
  for (const value of buffer) {
    crc ^= value;
    for (let bit = 0; bit < 8; bit += 1) {
      crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([length, body, crc]);
}

const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(width, 0);
ihdr.writeUInt32BE(height, 4);
ihdr[8] = 8;
ihdr[9] = 6;
const raw = Buffer.alloc((width * 4 + 1) * height);
for (let y = 0; y < height; y += 1) {
  rgba.copy(raw, y * (width * 4 + 1) + 1, y * width * 4, (y + 1) * width * 4);
}
const png = Buffer.concat([
  Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
  chunk("IHDR", ihdr),
  chunk("IDAT", zlib.deflateSync(raw)),
  chunk("IEND", Buffer.alloc(0))
]);
fs.writeFileSync(path.join(root, "assets/sprites.png"), png);
console.log(`sprites ${width}x${height} frames ${FRAME_NAMES.length}`);
